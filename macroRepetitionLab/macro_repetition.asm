; Macro repetition laboratory.
; Learn %rep, %endrep, %exitrep, and %assign.
; Build with: nrun macro_repetition.asm

section .data

; Generate bytes 5, 7, 9, 11 using macro repetition.
numbers:
%assign n 5
%rep 4
    db n
    %assign n n+2
%endrep
numbers_length equ $ - numbers

; Generate Fibonacci numbers up to 100000 as 32-bit values.
fibonacci:
%assign i 1
%assign j 1
%rep 100
    %if j > 100000
        %exitrep
    %endif
    dd j
    %assign k i+j
    %assign i j
    %assign j k
%endrep
fib_count equ ($ - fibonacci) / 4

; Generate 8 words with values 1 through 8.
word_values:
%assign value 1
%rep 8
    dw value
    %assign value value+1
%endrep

message db "Macro repetition demo", 10
message_len equ $ - message
numbers_label db "Generated bytes: 5, 7, 9, 11", 10
numbers_label_len equ $ - numbers_label
fib_label db "Fibonacci values generated: "
fib_label_len equ $ - fib_label
newline db 10

section .bss
number_buffer resb 16

section .text
    global _start

_start:
    ; Print the title.
    mov eax, 4
    mov ebx, 1
    mov ecx, message
    mov edx, message_len
    int 0x80

    ; Print the generated byte values.
    mov eax, 4
    mov ebx, 1
    mov ecx, numbers_label
    mov edx, numbers_label_len
    int 0x80

    ; Print the Fibonacci count label.
    mov eax, 4
    mov ebx, 1
    mov ecx, fib_label
    mov edx, fib_label_len
    int 0x80

    ; Print fib_count as a decimal number.
    mov eax, fib_count
    call print_uint

    ; Print a newline.
    mov eax, 4
    mov ebx, 1
    mov ecx, newline
    mov edx, 1
    int 0x80

    ; Exit the program.
    mov eax, 1
    xor ebx, ebx
    int 0x80

; Print unsigned integer in EAX followed by no newline.
print_uint:
    push ebx
    push ecx
    push edx
    push esi

    mov esi, number_buffer
    add esi, 15
    mov byte [esi], 0
    mov ebx, 10

    ; Handle zero explicitly.
    test eax, eax
    jnz .convert
    dec esi
    mov byte [esi], '0'
    jmp .write

.convert:
    xor edx, edx
    div ebx
    add dl, '0'
    dec esi
    mov [esi], dl
    test eax, eax
    jnz .convert

.write:
    mov eax, 4
    mov ebx, 1
    mov ecx, esi
    mov edx, number_buffer
    add edx, 15
    sub edx, esi
    int 0x80

    pop esi
    pop edx
    pop ecx
    pop ebx
    ret
